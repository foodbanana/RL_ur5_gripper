"""Build the Husky rail USD: a fixed rail and a carriage on a driven prismatic joint (no simulator needed).

The data collection repo moved the Husky kinematically along a straight line. A teleported kinematic body does not
carry a robot fixed to it by a joint in PhysX (the robot stayed put), so the motion is a mechanism here instead: an
articulation with a rail fixed to the world and a ``carriage`` body (the Husky base_link pose, the chassis mass) on a
prismatic joint along x, position-driven by the task to the trajectory. The Husky's meshes ride on the carriage;
the robot is fixed to it like on the Stewart top plate.

Usage (from the repository root):

    uv run python scripts/build_husky_rail_usd.py
"""

import sys
from pathlib import Path

from pxr import Gf, Usd, UsdGeom, UsdPhysics

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

ROOT = "/husky_rail"
CHASSIS_MASS = 46.0  # Husky A200 chassis (URDF), wheels not modeled
TRAVEL = 1.0  # prismatic range +-TRAVEL [m], more than the trajectory needs


def main():
    out = Path(__file__).resolve().parents[1] / "src/drone_grasp_rl/assets/data/bases/husky/husky_rail.usda"
    stage = Usd.Stage.CreateNew(str(out))
    stage.SetMetadata("metersPerUnit", 1.0)
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
    stage.SetDefaultPrim(UsdGeom.Xform.Define(stage, ROOT).GetPrim())
    stage.SetMetadata("comment", "Generated by scripts/build_husky_rail_usd.py. Do not edit.")
    ident = Gf.Quatf(1.0, 0.0, 0.0, 0.0)

    def body(path, mass, inertia):
        xf = UsdGeom.Xform.Define(stage, path)
        xf.AddTranslateOp().Set(Gf.Vec3d(0.0, 0.0, 0.0))
        xf.AddOrientOp().Set(ident)
        prim = xf.GetPrim()
        UsdPhysics.RigidBodyAPI.Apply(prim)
        m = UsdPhysics.MassAPI.Apply(prim)
        m.CreateMassAttr(mass)
        m.CreateDiagonalInertiaAttr(Gf.Vec3f(*inertia))
        m.CreateCenterOfMassAttr(Gf.Vec3f(0.0, 0.0, 0.0))
        return prim

    rail = body(f"{ROOT}/rail", 1.0, (0.01, 0.01, 0.01))
    UsdPhysics.ArticulationRootAPI.Apply(rail)  # rigid root, fixed to the world by the task (fix_root_link)
    carriage = body(f"{ROOT}/carriage", CHASSIS_MASS, (1.0, 1.5, 2.0))
    joint = UsdPhysics.PrismaticJoint.Define(stage, f"{ROOT}/joints/drive")
    joint.CreateBody0Rel().SetTargets([rail.GetPath()])
    joint.CreateBody1Rel().SetTargets([carriage.GetPath()])
    joint.CreateLocalPos0Attr().Set(Gf.Vec3f(0.0, 0.0, 0.0))
    joint.CreateLocalRot0Attr().Set(ident)
    joint.CreateLocalPos1Attr().Set(Gf.Vec3f(0.0, 0.0, 0.0))
    joint.CreateLocalRot1Attr().Set(ident)
    joint.CreateAxisAttr("X")
    joint.CreateLowerLimitAttr(-TRAVEL)
    joint.CreateUpperLimitAttr(TRAVEL)
    drive = UsdPhysics.DriveAPI.Apply(joint.GetPrim(), "linear")
    drive.CreateTypeAttr("force")
    stage.GetRootLayer().Save()
    print(f"[husky_rail] wrote {out}")


if __name__ == "__main__":
    main()
