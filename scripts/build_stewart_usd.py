"""Build the closed-loop Stewart platform USD from ``assets/stewart.py`` (no simulator needed).

One articulation, rooted at the base plate (the task fixes it to the world):

    base_plate --U--> leg_i_gimbal --U--> leg_i_cylinder --P (driven)--> leg_i_rod --S--> top_plate

``U`` = the two revolute joints of a universal joint at the base anchor, ``P`` = the leg actuator along the leg,
``S`` = a spherical joint at the top anchor. Leg 0's spherical joint is part of the articulation tree (it carries the
top plate); legs 1-5 close the loops with spherical joints excluded from the articulation (maximal-coordinate
constraints on PhysX; on Newton, ``MjcEqualityConnectAPI`` makes them MuJoCo CONNECT equalities with a stiff
``mjc:solref``). Prismatic joint position 0 is the leg length of the center pose; the targets come from the inverse
kinematics (:func:`drone_grasp_rl.assets.stewart.leg_lengths`).

Only the plates collide. Prim ``top_plate`` has its origin at the rotation center (top surface center), where the
robot base mounts.

Usage (from the repository root):

    uv run python scripts/build_stewart_usd.py
"""

import math
import sys
from pathlib import Path

import numpy as np
from pxr import Gf, Sdf, Usd, UsdGeom, UsdPhysics, UsdShade

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from drone_grasp_rl.assets import stewart as st  # noqa: E402

ROOT = "/stewart"
COLORS = {
    "base": (0.35, 0.35, 0.37),
    "top": (0.25, 0.42, 0.62),
    "cylinder": (0.15, 0.15, 0.16),
    "rod": (0.75, 0.76, 0.78),
}


def quat_z_to(d: np.ndarray) -> Gf.Quatf:
    """Rotation taking +z to the unit vector d."""
    d = d / np.linalg.norm(d)
    c = float(d[2])
    if c < -1 + 1e-9:
        return Gf.Quatf(0.0, 1.0, 0.0, 0.0)
    axis = np.cross([0.0, 0.0, 1.0], d)
    w = math.sqrt((1 + c) / 2)
    v = axis / (2 * w)
    return Gf.Quatf(w, float(v[0]), float(v[1]), float(v[2]))


def material(stage, name, rgb):
    mat = UsdShade.Material.Define(stage, f"{ROOT}/Looks/{name}")
    shader = UsdShade.Shader.Define(stage, f"{ROOT}/Looks/{name}/Shader")
    shader.CreateIdAttr("UsdPreviewSurface")
    shader.CreateInput("diffuseColor", Sdf.ValueTypeNames.Color3f).Set(Gf.Vec3f(*rgb))
    shader.CreateInput("roughness", Sdf.ValueTypeNames.Float).Set(0.6)
    mat.CreateSurfaceOutput().ConnectToSource(shader.ConnectableAPI(), "surface")
    return mat


def body(stage, path, pos, rot, mass, inertia):
    xf = UsdGeom.Xform.Define(stage, path)
    xf.AddTranslateOp().Set(Gf.Vec3d(*[float(v) for v in pos]))
    xf.AddOrientOp().Set(rot)
    prim = xf.GetPrim()
    UsdPhysics.RigidBodyAPI.Apply(prim)
    m = UsdPhysics.MassAPI.Apply(prim)
    m.CreateMassAttr(float(mass))
    m.CreateDiagonalInertiaAttr(Gf.Vec3f(*[float(v) for v in inertia]))
    m.CreateCenterOfMassAttr(Gf.Vec3f(0.0, 0.0, 0.0))
    return prim


def cylinder(stage, path, radius, height, z_center, mat, collide=False):
    cyl = UsdGeom.Cylinder.Define(stage, path)
    cyl.CreateRadiusAttr(float(radius))
    cyl.CreateHeightAttr(float(height))
    cyl.CreateAxisAttr("Z")
    cyl.AddTranslateOp().Set(Gf.Vec3d(0.0, 0.0, float(z_center)))
    UsdShade.MaterialBindingAPI.Apply(cyl.GetPrim()).Bind(mat)
    if collide:
        UsdPhysics.CollisionAPI.Apply(cyl.GetPrim())
    return cyl


def cyl_inertia(mass, radius, length):
    side = mass * (3 * radius**2 + length**2) / 12
    return (side, side, mass * radius**2 / 2)


def joint(stage, kind, path, body0, body1, pos0, rot0, pos1, rot1, axis=None, exclude=False):
    j = kind.Define(stage, path)
    j.CreateBody0Rel().SetTargets([body0])
    j.CreateBody1Rel().SetTargets([body1])
    j.CreateLocalPos0Attr().Set(Gf.Vec3f(*[float(v) for v in pos0]))
    j.CreateLocalRot0Attr().Set(rot0)
    j.CreateLocalPos1Attr().Set(Gf.Vec3f(*[float(v) for v in pos1]))
    j.CreateLocalRot1Attr().Set(rot1)
    if axis is not None:
        j.CreateAxisAttr(axis)
    if exclude:
        j.CreateExcludeFromArticulationAttr().Set(True)
    return j


def main():
    out = st.STEWART_USD_PATH
    out.parent.mkdir(parents=True, exist_ok=True)
    stage = Usd.Stage.CreateNew(str(out))
    stage.SetMetadata("metersPerUnit", 1.0)
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
    root = UsdGeom.Xform.Define(stage, ROOT).GetPrim()
    stage.SetDefaultPrim(root)
    stage.SetMetadata(
        "comment", "Generated by scripts/build_stewart_usd.py from drone_grasp_rl/assets/stewart.py. Do not edit."
    )
    mats = {k: material(stage, k, v) for k, v in COLORS.items()}
    ident = Gf.Quatf(1.0, 0.0, 0.0, 0.0)

    b, p = (a.numpy().astype(np.float64) for a in st.anchors())
    top_center = np.array([0.0, 0.0, st.HEIGHT])
    tops = p + top_center
    l0 = np.linalg.norm(tops - b, axis=1)
    assert np.allclose(l0, l0[0]), "the center pose must give equal legs"
    l0 = float(l0[0])

    # plates
    bt, tt = st.BASE_PLATE["thickness"], st.TOP_PLATE["thickness"]
    base = body(
        stage, f"{ROOT}/base_plate", (0, 0, 0), ident, st.BASE_PLATE_MASS,
        cyl_inertia(st.BASE_PLATE_MASS, st.BASE_PLATE["radius"], bt),
    )  # fmt: skip
    UsdPhysics.ArticulationRootAPI.Apply(base)  # a rigid root: Isaac Lab fixes it to the world (fix_root_link)
    cylinder(stage, f"{ROOT}/base_plate/geom", st.BASE_PLATE["radius"], bt, bt / 2, mats["base"], collide=True)
    top = body(
        stage, f"{ROOT}/top_plate", top_center, ident, st.TOP_PLATE_MASS,
        cyl_inertia(st.TOP_PLATE_MASS, st.TOP_PLATE["radius"], tt),
    )  # fmt: skip
    cylinder(stage, f"{ROOT}/top_plate/geom", st.TOP_PLATE["radius"], tt, -tt / 2, mats["top"], collide=True)

    half_len = (st.LEG_MAX + 0.05) / 2  # cylinder and rod length: the rod stays inside the cylinder at full stroke
    for i in range(6):
        d = (tops[i] - b[i]) / l0
        q = quat_z_to(d)
        g = body(stage, f"{ROOT}/leg_{i}_gimbal", b[i], q, st.GIMBAL_MASS, (5e-4, 5e-4, 5e-4))
        cyl = body(
            stage, f"{ROOT}/leg_{i}_cylinder", b[i], q, st.LEG_CYLINDER_MASS,
            cyl_inertia(st.LEG_CYLINDER_MASS, st.LEG_CYLINDER_RADIUS, half_len),
        )  # fmt: skip
        cylinder(
            stage, f"{ROOT}/leg_{i}_cylinder/geom", st.LEG_CYLINDER_RADIUS, half_len, half_len / 2, mats["cylinder"]
        )
        # rod frame = cylinder frame shifted by the extension; its tip (the top joint) at z = l0
        rod = body(
            stage, f"{ROOT}/leg_{i}_rod", b[i], q, st.LEG_ROD_MASS,
            cyl_inertia(st.LEG_ROD_MASS, st.LEG_ROD_RADIUS, half_len),
        )  # fmt: skip
        cylinder(stage, f"{ROOT}/leg_{i}_rod/geom", st.LEG_ROD_RADIUS, half_len, l0 - half_len / 2, mats["rod"])
        jdir = f"{ROOT}/joints"
        # universal joint: two revolutes, x then y of the leg frame
        joint(
            stage,
            UsdPhysics.RevoluteJoint,
            f"{jdir}/leg_{i}_u1",
            base.GetPath(),
            g.GetPath(),
            b[i],
            q,
            (0, 0, 0),
            ident,
            "X",
        )
        joint(
            stage,
            UsdPhysics.RevoluteJoint,
            f"{jdir}/leg_{i}_u2",
            g.GetPath(),
            cyl.GetPath(),
            (0, 0, 0),
            ident,
            (0, 0, 0),
            ident,
            "Y",
        )
        slide = joint(
            stage, UsdPhysics.PrismaticJoint, f"{jdir}/leg_{i}", cyl.GetPath(), rod.GetPath(),
            (0, 0, 0), ident, (0, 0, 0), ident, "Z",
        )  # fmt: skip
        slide.CreateLowerLimitAttr(float(st.LEG_MIN - l0))
        slide.CreateUpperLimitAttr(float(st.LEG_MAX - l0))
        drive = UsdPhysics.DriveAPI.Apply(slide.GetPrim(), "linear")
        drive.CreateTypeAttr("force")
        drive.CreateStiffnessAttr(float(st.LEG_STIFFNESS))
        drive.CreateDampingAttr(float(st.LEG_DAMPING))
        drive.CreateMaxForceAttr(float(st.LEG_FORCE_LIMIT))
        # top: spherical joint at the rod tip = top anchor; frames aligned in the center pose
        loop = joint(
            stage, UsdPhysics.SphericalJoint, f"{jdir}/leg_{i}_top", rod.GetPath(), top.GetPath(),
            (0, 0, l0), ident, p[i], q, exclude=i > 0,
        )  # fmt: skip
        if i > 0:
            # Newton (MuJoCo): the loop as an equality CONNECT with a stiff reference (the default 0.02 s let the
            # loops open by 22 mm and the platform shake); PhysX ignores mjc:* and keeps the excluded joint
            prim = loop.GetPrim()
            prim.AddAppliedSchema("MjcEqualityConnectAPI")
            prim.CreateAttribute("mjc:solref", Sdf.ValueTypeNames.DoubleArray).Set([0.005, 1.0])
            prim.CreateAttribute("mjc:solimp", Sdf.ValueTypeNames.DoubleArray).Set([0.95, 0.99, 0.001, 0.5, 2.0])
    stage.GetRootLayer().Save()
    print(f"[stewart] wrote {out.relative_to(Path.cwd()) if out.is_relative_to(Path.cwd()) else out}")
    print(f"[stewart] center-pose leg length {l0:.4f} m, stroke {st.LEG_MIN - l0:+.3f} .. {st.LEG_MAX - l0:+.3f} m")


if __name__ == "__main__":
    main()
